"""CSV inputs for the pgfplots figures in paper/essay/essay.tex, plus essay-only numbers."""
import json, pathlib
import pandas as pd

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA, RES, OUT = ROOT / "data", ROOT / "results", ROOT / "paper/essay/data"
BRANDS = ["Caltex", "Esso", "PetroChina", "Shell", "Sinopec"]


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    h = pd.read_csv(DATA / "hk_daily.csv", parse_dates=["date"])
    w = h[h.grade == "standard"].pivot(index="date", columns="brand", values="price")[BRANDS]
    win = w.loc["2026-02-01":"2026-05-31"].copy()
    win.insert(0, "day", (win.index - pd.Timestamp("2026-02-01")).days)
    win.to_csv(OUT / "fig1_steps.csv", index=False)

    m = pd.read_csv(RES / "hk_margin_monthly.csv", parse_dates=["month"])
    m["t"] = m.month.dt.year + (m.month.dt.month - 1) / 12
    m[["t", "import", "duty", "margin", "posted"]].round(3).to_csv(OUT / "fig2_margin.csv", index=False)

    by = pd.read_csv(RES / "hk_by_year.csv")
    pd.DataFrame({"year": by.year, "up": by.episodes_up.astype(int), "down": (by.episodes - by.episodes_up).astype(int)}).to_csv(OUT / "fig3_years.csv", index=False)

    irf = pd.read_csv(RES / "passthrough_irf.csv")
    wide = irf.pivot(index="week", columns="market", values=["rise", "fall"])
    wide.columns = [f"{m.split()[0].lower()}_{k}" for k, m in wide.columns]
    wide.reset_index().round(4).to_csv(OUT / "fig4_pt.csv", index=False)

    p = pd.read_csv(RES / "perth_daily.csv", parse_dates=["date"]).set_index("date").loc["2025-06-01":"2025-08-31"]
    p = p.assign(day=(p.index - pd.Timestamp("2025-06-01")).days)[["day", "p10", "median", "p90"]]
    p.round(2).to_csv(OUT / "fig5_perth.csv", index=False)

    d = pd.read_csv(DATA / "hk_walkin_discounts.csv", parse_dates=["date"])
    d = d[(d.grade == "standard") & (d.date == d.date.max())].set_index("brand")
    lo, hi = d.walkin_discount.idxmin(), d.walkin_discount.idxmax()
    n = {
        "essayDiscDate": d.index.size and pd.Timestamp(d.date.iloc[0]).strftime("%-d %B %Y"),
        "essayDiscLowBrand": lo, "essayDiscLow": f"{d.walkin_discount[lo]:.2f}",
        "essayDiscHighBrand": hi, "essayDiscHigh": f"{d.walkin_discount[hi]:.2f}",
        "essayNetLow": f"{d.net.min():.2f}", "essayNetHigh": f"{d.net.max():.2f}", "essayPump": f"{d.pump.max():.2f}",
    }
    (ROOT / "paper/essay/essay_numbers.tex").write_text("% Generated by scripts/export_essay_data.py. Do not edit.\n" +
        "\n".join(f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in n.items()) + "\n")
    print(json.dumps(n))


if __name__ == "__main__":
    main()
